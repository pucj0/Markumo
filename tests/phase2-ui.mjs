async function shown(locator) { await locator.waitFor({ state: 'visible', timeout: 5000 }) }
async function hidden(locator) { await locator.waitFor({ state: 'hidden', timeout: 5000 }) }
const editor = () => page.getByRole('textbox', { name: '文本编辑器', exact: true })
async function setTheme(theme) {
  await page.getByTitle('设置', { exact: true }).click()
  await page.getByLabel('颜色主题', { exact: true }).selectOption(theme)
  await page.getByRole('button', { name: '完成', exact: true }).click()
}
async function openCatalog(name, pin = false) {
  await page.keyboard.press('Control+p')
  await page.getByRole('textbox',{name:'搜索文件或命令'}).fill(name)
  await page.locator('.palrow').filter({hasText:name}).first().click()
  if(pin) await page.getByRole('tab',{name:new RegExp(name.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))}).dblclick()
}
async function contents(text) {
  await editor().click()
  await editor().press('Control+a')
  await page.keyboard.insertText(text)
  await page.waitForFunction(expected => document.querySelector('.status').textContent.includes(`${expected.toLocaleString()} 字符`), text.length)
}
async function test(name, run) {
  page = await browser.newPage({ viewport: { width: 1200, height: 780 } })
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto(demoUrl.href)
  await shown(editor())
  await run()
  results.push({ name, result: 'PASS' })
  console.log(`PASS ${name}`)
  await page.close()
}

